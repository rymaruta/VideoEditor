/** 「|」を外した文と、改行してよい所(文字の位置) */
export function parseCorpus(line: string): { text: string; allowed: Set<number> } {
  const allowed = new Set<number>()
  let text = ''
  for (const ch of [...line]) {
    if (ch === '|') allowed.add([...text].length)
    else text += ch
  }
  return { text, allowed }
}
